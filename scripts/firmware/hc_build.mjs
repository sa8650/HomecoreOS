/**
 * Generates firmware/homecoreos_esp32/hc_build.h before an arduino-cli build.
 *
 * Only public values end up in the image: the API origin, the two TLS trust
 * anchors and the firmware signing public key. Nothing secret is read here, and
 * a missing value is written as an empty string so the firmware reports
 * "not configured" instead of silently accepting anything.
 *
 *   node scripts/firmware/hc_build.mjs
 *
 * Environment (all optional):
 *   HC_FW_VERSION      version string compiled into the image (default: package version)
 *   HC_API_BASE        API origin (default: https://homecoreos.pages.dev)
 *   HC_CA_API_PEM      PEM bundle for the API origin (default: ca_api_bundle.pem)
 *   HC_CA_MQTT_PEM     PEM root for the broker (default: ca_mqtt_root.pem)
 *   HC_FW_PUBKEY       base64 Ed25519 public key, 44 characters (default: empty = keyless)
 *   HC_FW_SIGNING_ALG  ed25519 | ecdsa-p256-sha256 | none (default: ed25519 when a key is set)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const firmwareDir = resolve(here, '../../firmware/homecoreos_esp32');

function pem(envName, file, required) {
  const inline = process.env[envName];
  const raw = inline !== undefined && inline !== '' ? inline : (existsSync(join(firmwareDir, file)) ? readFileSync(join(firmwareDir, file), 'utf8') : '');
  const text = String(raw).replace(/\r\n/g, '\n').trim();
  if (text && !text.includes('-----BEGIN CERTIFICATE-----')) {
    throw new Error(`${envName} does not contain a PEM certificate`);
  }
  if (!text && required) throw new Error(`${envName} is required but ${file} is missing`);
  return text;
}

const version = process.env.HC_FW_VERSION || readFileSync(resolve(here, '../../package.json'), 'utf8').match(/"version":\s*"([^"]+)"/)[1];
if (!/^[A-Za-z0-9._+-]{1,32}$/.test(version)) throw new Error(`HC_FW_VERSION "${version}" is not a valid image version`);

const apiBase = process.env.HC_API_BASE || 'https://homecoreos.pages.dev';
if (!/^https:\/\/[a-z0-9.-]+(:\d+)?$/i.test(apiBase)) throw new Error(`HC_API_BASE "${apiBase}" must be an https origin`);

const key = String(process.env.HC_FW_PUBKEY || '').trim();
const alg = process.env.HC_FW_SIGNING_ALG || (key ? 'ed25519' : 'none');
if (!['ed25519', 'ecdsa-p256-sha256', 'none'].includes(alg)) {
  throw new Error(`HC_FW_SIGNING_ALG "${alg}" must be ed25519, ecdsa-p256-sha256 or none`);
}
if (key && alg === 'none') throw new Error('HC_FW_SIGNING_ALG is none but HC_FW_PUBKEY is set; use ed25519 or unset the key');
if (key && !/^[A-Za-z0-9+/]{43}=$/.test(key)) {
  throw new Error('HC_FW_PUBKEY must be the base64 of the raw 32-byte Ed25519 public key (44 characters ending in =)');
}
if (alg === 'ed25519' && !key) throw new Error('HC_FW_SIGNING_ALG is ed25519 but HC_FW_PUBKEY is empty');

const caApi = pem('HC_CA_API_PEM', 'ca_api_bundle.pem', true);
const caMqtt = pem('HC_CA_MQTT_PEM', 'ca_mqtt_root.pem', true);

const cstr = (value) => JSON.stringify(value); // Arduino accepts \n escapes inside a C string literal

const header = `#pragma once
// Generated by scripts/firmware/hc_build.mjs. Do not edit; rebuild to change.
#define HOMECOREOS_FW_VERSION ${cstr(version)}
#define HOMECOREOS_API_BASE ${cstr(apiBase)}
#define HOMECOREOS_CA_API_PEM ${cstr(caApi)}
#define HOMECOREOS_CA_MQTT_PEM ${cstr(caMqtt)}
#define HOMECOREOS_FW_SIGNING_PUBKEY ${cstr(key)}
#define HOMECOREOS_FW_SIGNING_ALG ${cstr(alg)}
`;

writeFileSync(join(firmwareDir, 'hc_build.h'), header);
console.log(`hc_build.h written: version ${version}, api ${apiBase}, signing ${alg === 'none' ? 'not configured' : alg}`);
